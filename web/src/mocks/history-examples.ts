/** The examples as stories, timed against now, for the businesses in scope. */
export function exampleStories(workspace: string | null | undefined, now = Date.now()): HistoryStory[] {
  return EXAMPLES.filter((example) => !workspace || example.lane.startsWith(`${workspace}/`)).map(({ minutesAgo, ...example }) => {
    const at = new Date(now - minutesAgo * MINUTE).toISOString();
    const [ws = ''] = example.lane.split('/');
    return {
      source: 'run',
      status: example.verdict === 'checked' ? 'succeeded_verified' : 'succeeded_unverified',
      reason: null,
      detail: null,
      proof: null,
      steps: [],
      technical: { run_id: example.id, flow: example.who.kind === 'flow' ? example.who.id : null, effect: example.action === 'pay' ? 'pay' : example.action === 'read' ? 'read' : 'commit', cost: { tokens: 3_400, usd: 0.01 } },
      why: { trigger: null, text: null, approval: null },
      ...example,
      at,
      started_at: new Date(now - minutesAgo * MINUTE - 40_000).toISOString(),
      workspace: ws,
      workspace_name: NAMES[ws] ?? ws,
    };
  });
}
